def render(spec):
    rows = spec["px"]
    h = len(rows)
    w = len(rows[0])
    pal = spec["pal"]
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            hexc = pal.get(ch)
            if not hexc:
                raise SystemExit("调色板里没有 '%s'（在 %r 这行）" % (ch, row))
            img.putpixel((x, y), (int(hexc[1:3], 16), int(hexc[3:5], 16), int(hexc[5:7], 16), 255))
    return img


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    # 清掉旧的，避免改名后留垃圾
    for f in os.listdir(outdir):
        if f.endswith(".png"):
            os.remove(os.path.join(outdir, f))
    for name in SPRITES:
        img = render(SPRITES[name])
        img.save(os.path.join(outdir, name + ".png"))
        print("  %-12s %2dx%-2d" % (name, img.width, img.height))
    print("共 %d 个花草动物素材 -> %s" % (len(SPRITES), outdir))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT)
